#!/usr/bin/env python3
"""Deterministically export the shared API/MCP contract; --check rejects drift."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from modelbuilder.api import create_app
from modelbuilder.models import ModelProject, OPERATIONS, operation_catalog
from modelbuilder.service import OperationService

ROOT = Path(__file__).resolve().parents[1]


def json_text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def generated_files():
    service = OperationService(":memory:")
    try:
        openapi = create_app(service=service, tokens={}).openapi()
    finally:
        service.store.close()
    catalog = operation_catalog()
    documentation = [
        "# Native MCP tool catalog", "",
        "Generated by `scripts/export_contracts.py` from the operation service contract. Do not edit by hand.", "",
        "The standalone MCP server calls the same authenticated HTTP operation service used by the IDE.",
        "MCP runs independently of the IDE. Tool names replace operation dots with underscores.",
        "Read-only identities can discover the catalog but cannot invoke mutations, including through guessed tool names.",
        "All mutations require `idempotency_key`; updates require the documented expected revision.",
        "The complete payload schemas are in [operation-catalog.json](operation-catalog.json) and [openapi.json](openapi.json).", "",
        "| MCP tool | Shared operation | Required scope | Description |",
        "|---|---|---|---|",
    ]
    for operation in catalog:
        documentation.append(f"| `{operation['name'].replace('.', '_')}` | `{operation['name']}` | `{', '.join(operation['required_scopes'])}` | {operation['description']} |")
    documentation += ["", "Remote execution/spending, publication, discovery, and public recipe forking remain unavailable.",
                      "A configured ZenML backend is required for execution and model records. The service never returns fabricated native runs.",
                      "Resume advances the same canonical recipe identity to a new immutable revision and digest; parent runs retain their historical revision.", ""]
    request_schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema", "title": "ModelBuilderOperationRequest",
        "oneOf": [{"type": "object", "properties": {"operation": {"const": name}, "payload": spec.input_schema},
                   "required": ["operation", "payload"], "additionalProperties": False}
                  for name, spec in sorted(OPERATIONS.items())],
    }
    return {
        "docs/openapi.json": json_text(openapi),
        "docs/operation-catalog.json": json_text({"schema_version": "0", "operations": catalog}),
        "docs/MCP_TOOLS.md": "\n".join(documentation),
        "schemas/operation.v0.schema.json": json_text(request_schema),
        "schemas/project.v0.schema.json": json_text({"$schema": "https://json-schema.org/draft/2020-12/schema", **ModelProject.model_json_schema()}),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report generated-file drift without writing")
    args = parser.parse_args()
    drift = []
    for relative, content in generated_files().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                drift.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(relative)
    if drift:
        raise SystemExit("Generated contract drift: " + ", ".join(drift))
    if args.check:
        print("Generated API, MCP, and domain contracts match implementation.")


if __name__ == "__main__":
    main()
