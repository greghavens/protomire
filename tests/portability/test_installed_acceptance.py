@pytest.mark.parametrize("defect", ["missing", "hash", "size", "row_missing", "duplicate", "metadata_unlisted",
                                   "unapproved_metadata", "unapproved_wrapper", "missing_wrapper", "record_self_hash", "malformed"])
def test_installed_record_is_complete_and_narrowly_allowlisted(installed, defect):
    record = installed.site / "modelbuilder-0.1.0.dist-info/RECORD"
    rows = list(csv.reader(record.read_text().splitlines()))
    if defect == "missing":
        record.unlink()
    elif defect == "missing_wrapper":
        (installed.venv / "bin/modelbuilder-service").unlink()
    elif defect in {"metadata_unlisted", "unapproved_metadata", "unapproved_wrapper"}:
        name = ("../../../bin/unapproved-tool" if defect == "unapproved_wrapper" else
                "modelbuilder-0.1.0.dist-info/unapproved.json")
