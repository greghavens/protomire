def make_environments(work):
    for role in harness.ROLES:
        for kind in harness.KINDS:
            env = work / f"{role}-{kind}"
            site = env / "lib/python3.12/site-packages"
            site.mkdir(parents=True)
            (site / "dependency.py").write_text("original")
            (env / "lib64").symlink_to("lib", target_is_directory=True)


@pytest.mark.parametrize("mutation", ["dependency", "bytecode", "deleted", "link"])
def test_all_four_environment_snapshots_detect_mutations(tmp_path, mutation):
    make_environments(tmp_path)
    before = harness.installed_snapshot(tmp_path)
    assert all(value["lib64"] == {"kind": "directory_symlink", "target": "lib"} for value in before.values())
    root = tmp_path / "origin-backend"
    site = harness.site_path(root)
    if mutation == "dependency":
        (site / "dependency.py").write_text("changed")
    elif mutation == "bytecode":
        (site / "generated.pyc").write_bytes(b"bytecode")
    elif mutation == "deleted":
        shutil.rmtree(root)
    else:
        (root / "lib64").unlink()
        (root / "lib64").symlink_to(tmp_path, target_is_directory=True)
    after = harness.installed_snapshot(tmp_path, strict=False)
    assert before != after
    assert before["replay-backend"] == after["replay-backend"]
    if mutation in {"deleted", "link"}:
        assert "inventory_error" in after["origin-backend"]


