def test_execution_failure_keeps_original_error_and_runs_after_capture(tmp_path):
    class BrokenExecution(harness.Acceptance):
        def stage(self):
            self.frozen = {}
        def install(self):
            make_environments(self.work)
        def execute_custom(self):
            raise RuntimeError("original workload failure")
        def capture_after(self):
            self.save("installed-after.json", harness.installed_snapshot(self.work))
            self.save("after-capture-errors.json", [{"stage": "cleanup", "error": "also failed"}])
            return [{"stage": "cleanup", "error": "also failed"}]
    run = BrokenExecution.__new__(BrokenExecution)
    run.work = tmp_path / "work"
    run.evidence, run.logs = run.work / "evidence", run.work / "logs"
    run.evidence.mkdir(parents=True)
    run.logs.mkdir()
    with pytest.raises(RuntimeError, match="original workload failure"):
        run.run()
    assert run.read("failure.json")["message"] == "original workload failure"
    assert run.read("installed-before.json") == run.read("installed-after.json")
    receipt = run.read("receipt-sha256.json")
    assert "evidence/after-capture-errors.json" in receipt and "evidence/failure.json" in receipt
    assert not (run.evidence / "summary.json").exists()


